const COOKIE = "signalops_language";
const YEAR = 60 * 60 * 24 * 365;

function readCookie(): Language | null {
  if (typeof document === "undefined") return null;
  const m = document.cookie.match(new RegExp(`(?:^|; )${COOKIE}=(vi|en)`));
  return (m?.[1] as Language) ?? null;
}
function writeCookie(l: Language) {
  if (typeof document === "undefined") return;
  document.cookie = `${COOKIE}=${l}; path=/; max-age=${YEAR * 5}; SameSite=Lax`;
}

