const DICTS: Record<Language, Dict> = { en, vi };

type Ctx = {
  lang: Language;
  setLang: (l: Language) => void;
  t: (key: keyof typeof en) => string;
  formatCurrency: (n: number, currency?: string) => string;
  formatNumber: (n: number, opts?: Intl.NumberFormatOptions) => string;
  formatPercent: (n: number, digits?: number) => string;
  formatDate: (d: Date | string, opts?: Intl.DateTimeFormatOptions) => string;
};

const I18nContext = createContext<Ctx | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Language>("vi");
  useEffect(() => {
    const c = readCookie();
    if (c) setLangState(c);
  }, []);
  const setLang = useCallback((l: Language) => {
    setLangState(l);
    writeCookie(l);
  }, []);
  const value = useMemo<Ctx>(() => {
    const locale = lang === "vi" ? "vi-VN" : "en-US";
    const dict = DICTS[lang];
    return {
      lang,
      setLang,
      t: (k) => dict[k as string] ?? en[k] ?? (k as string),
      formatCurrency: (n, currency = "USD") =>
        new Intl.NumberFormat(locale, { style: "currency", currency, maximumFractionDigits: 2 }).format(n),
      formatNumber: (n, opts) => new Intl.NumberFormat(locale, opts).format(n),
      formatPercent: (n, digits = 2) =>
        new Intl.NumberFormat(locale, { style: "percent", minimumFractionDigits: digits, maximumFractionDigits: digits }).format(n / 100),
      formatDate: (d, opts) =>
        new Intl.DateTimeFormat(locale, opts ?? { day: "2-digit", month: "2-digit", year: "2-digit", hour: "2-digit", minute: "2-digit" }).format(typeof d === "string" ? new Date(d) : d),
    };
  }, [lang, setLang]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const c = useContext(I18nContext);
  if (!c) throw new Error("useI18n must be inside I18nProvider");
  return c;
}

